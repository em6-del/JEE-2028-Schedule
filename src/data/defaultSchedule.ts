export const DAYS_OF_WEEK: DayOfWeek[] = [
  'Monday',
  'Tuesday',
  'Wednesday',
  'Thursday',
  'Friday',
  'Saturday',
  'Sunday',
];

export function getDefaultScheduleForDay(day: DayOfWeek): DaySchedule {
  const isWeekend = day === 'Saturday' || day === 'Sunday';
  const preset = isWeekend ? 'weekend_deep_prep' : 'school_day';
  const baseSlots = isWeekend ? DEFAULT_WEEKEND_SLOTS : DEFAULT_SCHOOL_DAY_SLOTS;

  return {
    day,
    preset,
    slots: baseSlots.map((s) => ({ ...s, id: `${day.toLowerCase()}-${s.id}` })),
    dailyTargetHours: isWeekend ? 9 : 5.5,
    dailyTargetProblems: isWeekend ? 70 : 40,
    dailyNotes: isWeekend
      ? 'Focus on deep analytical questions and test analysis.'
      : 'Maintain consistency between school and evening JEE self-study.',
  };
}

export function getDefaultWeekSchedules(): Record<DayOfWeek, DaySchedule> {
  const scheduleMap = {} as Record<DayOfWeek, DaySchedule>;
  DAYS_OF_WEEK.forEach((day) => {
    scheduleMap[day] = getDefaultScheduleForDay(day);
  });
  return scheduleMap;
}

